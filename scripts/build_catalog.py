#!/usr/bin/env python3
"""Turn the GeoParquet files of export.py into a Portolan catalog.

Run with the Python of the portolan-cli tool environment (it has duckdb, pyarrow and PyYAML):

  ~/.local/share/uv/tools/portolan-cli/bin/python -I build_catalog.py <manifest.json> <catalog dir> <dsfl-ai dir>

Steps:
1. portolan clean + init (always from scratch), .portolan/config.yaml
2. .portolan/metadata.yaml for the root, the four subcatalogs and every collection: titles,
   descriptions, licence, providers, source and attribution come from the API configuration
   (entities/instances/services/<api>.yml and the providers)
3. portolan add . --force
4. collection.json: column descriptions (from the provider, without the API-only sentences) and
   the temporal extent
5. AGENTS.md for the root, the subcatalogs and the collections; every SQL recipe in them is run
   against the files first and the build stops if one fails
6. portolan readme, portolan check
"""

